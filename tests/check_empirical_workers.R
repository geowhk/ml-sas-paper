source(file.path(root,'05_empirical-study/R/mlsas_inference.R'))
suppressPackageStartupMessages(library(spdep))
nb<-cell2nb(2,2);S<-matrix(c(1,.2,.3,.4,.2,1,.5,.6,.3,.5,1,.7,.4,.6,.7,1),4)
P<-cbind(1:4,c(2,1,4,3),4:1)
a<-mlsas_permutation_inference(nb,S,P,workers=1)
parallel_result<-mlsas_permutation_inference(nb,S,P,workers=2)
stopifnot(identical(a,parallel_result))
one<-mlsas_permutation_inference(nb,S,P[,1,drop=FALSE],workers=1)
stopifnot(one$global$nperm==1)
